export function translate(lang: Language, key: string, params?: Record<string, string>): string {
  let text = translations[lang]?.[key] ?? translations.en[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, v)
    }
  }
  return text
}
